# Using DFS


def print_as_grid(state):
    """Prints the 9 numbers as a clear 3x3 layout using basic indexes."""
    print("[", state[0], state[1], state[2], "]")
    print("[", state[3], state[4], state[5], "]")
    print("[", state[6], state[7], state[8], "]")
    print("-----------")

def dfs(state, goal, visited, path):
    # 1. Base Case: Goal Found
    if state == goal:
        path.append(state) # Add the final goal state to our path
        return True

    # 2. Add to visited and path trackers
    visited.add(state)
    path.append(state) # Save this state to the path list

    zero = state.index(0)
    zero_row = zero // 3
    moves = [-3, +3, -1, +1]

    for move in moves:
        new_pos = zero + move

        if new_pos >= 0 and new_pos <= 8:
            new_row = new_pos // 3

            # Simple horizontal wrap-around check
            if move == -1 or move == +1:
                if zero_row != new_row:
                    continue # Skip illegal moves

            # Swap elements simply
            new_state_list = list(state)
            new_state_list[zero] = new_state_list[new_pos]
            new_state_list[new_pos] = 0
            new_state = tuple(new_state_list)

            if new_state not in visited:
                if dfs(new_state, goal, visited, path):
                    return True

    # 3. Backtrack: If code reaches here, this state was a dead end!
    path.pop() # Remove the wrong state from our path list
    return False

# --- Run Setup ---
initial_board = (1, 2, 3, 4, 0, 6, 7, 5, 8)  # 0 is the blank space
goal_board    = (1, 2, 3, 4, 5, 6, 7, 8, 0)
visited_states = set()
solution_path = []

print("--- Running Simple DFS ---")
if dfs(initial_board, goal_board, visited_states, solution_path):
    print("\n--- CLEAN SOLUTION PATH FOUND! ---")

    # Print the saved steps one by one using a simple loop
    step = 0
    for board in solution_path:
        print("Step number:", step)
        print_as_grid(board)
        step = step + 1
else:
    print("No solution found.")


#Using IDFS

def print_as_grid(state):
    """Prints the 9 numbers as a clear 3x3 layout using simple indexes."""
    print("[", state[0], state[1], state[2], "]")
    print("[", state[3], state[4], state[5], "]")
    print("[", state[6], state[7], state[8], "]")
    print("-----------")

def dfs_limited(state, goal, limit, depth, visited):
    # 1. EVERY ITERATION STATE IS PRINTED HERE AS SOON AS SEARCH VISITS IT
    print("Depth -", depth)
    print_as_grid(state)

    # 2. Check if goal is reached
    if state == goal:
        print("\n=============================================")
        print(f"🎯 GOAL REACHED AT LEVEL / DEPTH: {depth}")
        print("=============================================")
        print("FINAL GOAL STATE:")
        print_as_grid(state)
        return True

    # 3. Check if depth limit has been reached
    if depth >= limit:
        return False

    # 4. Add to visited for the active path branch
    visited.add(state)

    zero = state.index(0)
    zero_row = zero // 3
    moves = [-3, +3, -1, +1]

    for move in moves:
        new_pos = zero + move

        if new_pos >= 0 and new_pos <= 8:
            new_row = new_pos // 3

            # Simple horizontal check: if moving left/right, rows must match
            if move == -1 or move == +1:
                if zero_row != new_row:
                    continue # Skip this illegal wrap-around move

            # Swap elements simply
            new_state_list = list(state)
            new_state_list[zero] = new_state_list[new_pos]
            new_state_list[new_pos] = 0
            new_state = tuple(new_state_list)

            if new_state not in visited:
                if dfs_limited(new_state, goal, limit, depth + 1, visited):
                    return True

    # 5. Backtrack: remove from visited
    visited.remove(state)
    return False

def iterative_deepening_search(initial_state, goal):
    depth_limit = 0
    while depth_limit <= 30:  # Safe safety-net limit
        print("====================================")
        print("STARTING SEARCH FOR DEPTH LIMIT:", depth_limit)
        print("====================================")
        visited = set()

        if dfs_limited(initial_state, goal, depth_limit, 0, visited):
            return True
        depth_limit += 1

    print("No solution found within constraints.")
    return False

