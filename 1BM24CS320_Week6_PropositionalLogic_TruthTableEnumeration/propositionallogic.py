from itertools import product
import re

# ---------- Parser: ~ (not), & (and), | (or), => (implies), <=> (iff) ----------
def tokenize(s):
    return re.findall(r'<=>|=>|[~&|()]|[A-Za-z_]\w*', s)

class Parser:
    def __init__(self, text):
        self.t = tokenize(text); self.i = 0
    def peek(self): return self.t[self.i] if self.i < len(self.t) else None
    def eat(self): self.i += 1; return self.t[self.i - 1]
    def parse(self):
        node = self.iff()
        if self.peek() is not None: raise ValueError("Bad sentence")
        return node
    def iff(self):
        l = self.imp()
        while self.peek() == '<=>': self.eat(); l = ('iff', l, self.imp())
        return l
    def imp(self):
        l = self.orr()
        if self.peek() == '=>': self.eat(); return ('imp', l, self.imp())
        return l
    def orr(self):
        l = self.andd()
        while self.peek() == '|': self.eat(); l = ('or', l, self.andd())
        return l
    def andd(self):
        l = self.neg()
        while self.peek() == '&': self.eat(); l = ('and', l, self.neg())
        return l
    def neg(self):
        if self.peek() == '~': self.eat(); return ('not', self.neg())
        if self.peek() == '(':
            self.eat(); n = self.iff()
            if self.eat() != ')': raise ValueError("Missing )")
            return n
        tok = self.eat()
        if tok is None or not re.match(r'[A-Za-z_]\w*$', tok): raise ValueError("Bad sentence")
        return ('sym', tok)

# ---------- PL-TRUE? : value of a sentence in a model ----------
def pl_true(node, m):
    op = node[0]
    if op == 'sym': return m[node[1]]
    if op == 'not': return not pl_true(node[1], m)
    a, b = pl_true(node[1], m), pl_true(node[2], m)
    if op == 'and': return a and b
    if op == 'or':  return a or b
    if op == 'imp': return (not a) or b
    if op == 'iff': return a == b

def get_symbols(node, out):
    if node[0] == 'sym':
        if node[1] not in out: out.append(node[1])
    else:
        for c in node[1:]: get_symbols(c, out)

# ---------- TT-ENTAILS? ----------
def tt_entails(kb, alpha, symbols):
    return tt_check_all(kb, alpha, symbols, {})

# ---------- TT-CHECK-ALL ----------
def tt_check_all(kb, alpha, symbols, model):
    if not symbols:
        if all(pl_true(s, model) for s in kb):
            return pl_true(alpha, model)
        return True
    P, rest = symbols[0], symbols[1:]
    return (tt_check_all(kb, alpha, rest, {**model, P: True}) and
            tt_check_all(kb, alpha, rest, {**model, P: False}))

def t(x): return "T" if x else "F"

# ---------- Main ----------
print("Use:  ~ not,  & and,  | or,  => implies,  <=> iff,  ( ) brackets")
n = int(input("How many sentences in KB? "))
kb_text, kb = [], []
for i in range(n):
    s = input(f"Enter KB sentence {i+1}: ")
    kb_text.append(s); kb.append(Parser(s).parse())

k = int(input("How many queries? "))
q_text, q_nodes = [], []
for j in range(k):
    s = input(f"Enter query {j+1}: ")
    q_text.append(s); q_nodes.append(Parser(s).parse())

symbols = []
for s in kb + q_nodes: get_symbols(s, symbols)
symbols.sort()

# ---------- FULL TRUTH TABLE ----------
cols = kb_text + ["KB"] + q_text
widths = [len(c) for c in cols]
sep = "-" * (2 * len(symbols) + 3 + sum(w + 3 for w in widths))

print("\nFULL TRUTH TABLE")
print(sep)
print(" ".join(symbols), "|", " | ".join(cols))
print(sep)
kb_models = []
for vals in product([True, False], repeat=len(symbols)):
    m = dict(zip(symbols, vals))
    row = [pl_true(s, m) for s in kb]
    kbv = all(row)
    if kbv: kb_models.append(m)
    values = row + [kbv] + [pl_true(q, m) for q in q_nodes]
    print(" ".join(t(m[s]) for s in symbols), "|",
          " | ".join(t(v).center(w) for v, w in zip(values, widths)))
print(sep)

print("\nModels where KB is true:")
for m in kb_models: print(" ", m)

print("\nENTAILMENT RESULTS")
for text, q in zip(q_text, q_nodes):
    print(f"Does KB entail ({text})?  ->", tt_entails(kb, q, symbols))