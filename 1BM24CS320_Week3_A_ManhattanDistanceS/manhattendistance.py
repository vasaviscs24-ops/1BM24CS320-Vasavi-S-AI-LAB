def get_manhattan_distance(board, goal):
    """Calculates the total Manhattan distance of all numbered tiles from their goal positions."""
    distance = 0
    for i, tile in enumerate(board):
        if tile == '_':
            continue
        # Find the target index of the current tile in the goal state
        goal_idx = goal.index(tile)

        # Convert flat indices to 2D coordinates (row, column)
        curr_row, curr_col = divmod(i, 3)
        goal_row, goal_col = divmod(goal_idx, 3)

        # Calculate absolute grid distance
        distance += abs(curr_row - goal_row) + abs(curr_col - goal_col)
    return distance

def get_neighbors(board_str):
    board = list(board_str)
    idx = board.index('_')
    r, c = divmod(idx, 3)
    moves = []
    # Valid moves for the blank: Up, Down, Left, Right
    for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
        nr, nc = r + dr, c + dc
        if 0 <= nr < 3 and 0 <= nc < 3:
            n_idx = nr * 3 + nc
            new_board = board.copy()
            new_board[idx], new_board[n_idx] = new_board[n_idx], new_board[idx]
            moves.append("".join(new_board))
    return moves

# Define Start and Goal States
start = "12348576_"
goal = "12345678_"

# A* Initialization: open_list stores tuples of (f, g, h, state)
h_start = get_manhattan_distance(start, goal)
open_list = [(h_start, 0, h_start, start)]
closed_list = {}
iteration = 1

while open_list:
    # Sort by lowest f-score, break ties with lowest g-score, then by state name alphabetically
    open_list.sort(key=lambda x: (x[0], x[1], x[3]))
    f, g, h, curr = open_list.pop(0)

    # Convert string representation to a 3x3 grid
    grid_lines = [curr[i:i+3] for i in range(0, 9, 3)]
    grid_formatted = "\n".join(" ".join(row) for row in grid_lines)

    # Print current trace
    print(f"--- Iteration {iteration} ---")
    print(f"Current Board (f={f}, g={g}, h={h}):\n{grid_formatted}")

    closed_list[curr] = (f, g, h)

    if curr == goal:
        print(f"Goal reached successfully in {g} moves!")
        break

    for neighbor in get_neighbors(curr):
        if neighbor in closed_list:
            continue

        nh = get_manhattan_distance(neighbor, goal)
        ng = g + 1
        nf = ng + nh

        # Update node in open_list if a shorter path is found
        exists = False
        for i, (of, og, oh, ostate) in enumerate(open_list):
            if ostate == neighbor:
                exists = True
                if nf < of:
                    open_list[i] = (nf, ng, nh, neighbor)
                break

        if not exists:
            open_list.append((nf, ng, nh, neighbor))

    # Output active list statuses
    print(f"Open List : {[x[3] for x in open_list]}")
    print(f"Closed List: {list(closed_list.keys())}\n")
    iteration += 1