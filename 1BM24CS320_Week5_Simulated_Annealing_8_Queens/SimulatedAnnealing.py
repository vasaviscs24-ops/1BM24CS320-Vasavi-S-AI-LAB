import random
import math

def calculate_cost(state):
    cost = 0
    for i in range(8):
        for j in range(i + 1, 8):
            if state[i] == state[j] or abs(state[i] - state[j]) == abs(i - j):
                cost += 1
    return cost

def generate_neighbours(state):
    neighbours = []
    for col in range(8):
        for row in range(8):
            if row != state[col]:
                neighbour = state.copy()
                neighbour[col] = row
                neighbours.append(neighbour)
    return neighbours

def print_grid(state):
    for row in range(8):
        for col in range(8):
            print("Q" if state[col] == row else ".", end=" ")
        print()

def accept(delta_e, temperature):
    return delta_e > 0 or random.random() < math.exp(delta_e / temperature)

def simulated_annealing():
    random.seed(10)

    current = [0, 1, 2, 3, 4, 5, 6, 7]
    current_cost = calculate_cost(current)
    best, best_cost = current.copy(), current_cost

    temperature = 1.0
    minimum_temperature = 0.01
    cooling_rate = 0.99

    print(f"Initial state | State = {current} | Cost = {current_cost}")
    print_grid(current)
    print()

    step = 1
    while temperature > minimum_temperature and best_cost != 0:
        neighbours = generate_neighbours(current)
        costs = [calculate_cost(n) for n in neighbours]

        min_cost = min(costs)
        next_state = random.choice([n for n, c in zip(neighbours, costs) if c == min_cost])
        next_cost = min_cost

        if accept(current_cost - next_cost, temperature):
            current, current_cost = next_state, next_cost
        else:
            i = random.randrange(len(neighbours))
            if accept(current_cost - costs[i], temperature):
                current, current_cost = neighbours[i], costs[i]

        if current_cost < best_cost:
            best, best_cost = current.copy(), current_cost

        print(f"Iteration {step:3d} | T = {temperature:.4f} | State = {current} | Cost = {current_cost} | Best cost = {best_cost}")
        print_grid(current)
        print()

        temperature *= cooling_rate
        step += 1

    print(f"Total steps taken: {step - 1}")
    print("Final best state:", best)
    print("Minimum cost:", best_cost)
    print("Solution found!" if best_cost == 0 else "Solution not found in this run.")

simulated_annealing()