# ---------- parser: "P(x, f(y))" -> ('P', 'x', ('f', 'y')) ----------
def parse(text):
    tokens = re.findall(r"[A-Za-z0-9_]+|[(),]", text)
    pos = 0

    def term():
        nonlocal pos
        name = tokens[pos]; pos += 1
        if pos < len(tokens) and tokens[pos] == "(":
            pos += 1
            args = [term()]
            while tokens[pos] == ",":
                pos += 1
                args.append(term())
            pos += 1                      # skip ')'
            return (name,) + tuple(args)
        return name

    result = term()
    if pos != len(tokens):
        raise ValueError("extra text after the expression")
    return result


