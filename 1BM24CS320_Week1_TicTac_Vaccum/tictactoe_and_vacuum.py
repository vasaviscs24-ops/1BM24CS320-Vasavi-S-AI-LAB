# TIC TAC TOE GAME
def display_board(board):
    print()

    for i in range(3):
        print(" | ".join(board[i]))

        if i < 2:
            print("--+---+--")

    print()


def check_win(board, player):

    # Check rows
    for i in range(3):
        if (board[i][0] == player and
            board[i][1] == player and
            board[i][2] == player):
            return True

    # Check columns
    for j in range(3):
        if (board[0][j] == player and
            board[1][j] == player and
            board[2][j] == player):
            return True

    # Check first diagonal
    if (board[0][0] == player and
        board[1][1] == player and
        board[2][2] == player):
        return True

    # Check second diagonal
    if (board[0][2] == player and
        board[1][1] == player and
        board[2][0] == player):
        return True

    return False


