def calculate_cost(state):
    cost = 0

    for i in range(4):
        for j in range(i + 1, 4):
            if (state[i] == state[j] or
                    abs(state[i] - state[j]) == abs(i - j)):
                cost += 1

    return cost


def generate_neighbours(state):
    neighbours = []

    for i in range(4):
        for j in range(i + 1, 4):
            neighbour = list(state)
            neighbour[i], neighbour[j] = neighbour[j], neighbour[i]
            neighbours.append(((i, j), tuple(neighbour)))

    return neighbours


# Function to print the board
def print_board(state):
    print("\nFinal Board:")

    for i in range(4):
        for j in range(4):
            if state[i] == j:
                print(" Q ", end="")
            else:
                print(" . ", end="")
        print()


def hill_climbing():
    current = (3, 1, 2, 0)
    step = 1

    while True:
        current_cost = calculate_cost(current)

        print("\nStep:", step)
        print("Current state:", current)
        print("Current cost:", current_cost)

        if current_cost == 0:
            print("Goal state reached!")
            print_board(current)
            return current

        neighbours = generate_neighbours(current)

        print("\nAll possible neighbours:")

        for pair, state in neighbours:
            print("Swap", pair, ":", state,
                  "Cost =", calculate_cost(state))

        neighbours.sort(
            key=lambda item: (calculate_cost(item[1]), item[0])
        )

        best_pair, best_state = neighbours[0]
        best_cost = calculate_cost(best_state)

        print("\nSelected neighbour:", best_state)
        print("Selected cost:", best_cost)

        if best_cost >= current_cost:
            print("No better neighbour. Stopping.")
            return current

        current = best_state
        step += 1


solution = hill_climbing()

print("\nFinal solution:", solution)
print("Final cost:", calculate_cost(solution))
print_board(solution)